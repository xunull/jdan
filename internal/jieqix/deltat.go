package jieqix

// ΔT = TT − UT，单位秒。地球自转不匀速，原子时走得稳、地球走得不稳，
// 两者的差就是 ΔT。
//
// 为什么必须做这一步：解「太阳视黄经 = 15°k」解出来的是 TT（力学时），
// 而人看的日历是 UT。少减一次 ΔT，2026 年就整体偏 69 秒——这足以把一个
// 卡在交节点前后一分钟内出生的人的年柱算翻，而且不会报任何错。
// 这是整条算法链里最容易漏、漏了又最难发现的一步。
//
// 用的是 Espenak–Meeus 分段多项式（NASA eclipse 网站公开版本，基于
// Morrison & Stephenson 2004）。选它是因为系数完全公开、可逐项核对。
//
// ⚠️ 已知偏差（对 internal/jieqix/testdata/deltat_ref.tsv 实测，
//
//	   该文件是 NAOJ 暦計算室的值，远期用 Stephenson 等 2020 模型 S2020）：
//
//		年     本实现(E–M)   NAOJ      差
//		1900     −2.06      −1.9     0.2 s
//		1929     24.15      24.4     0.3 s
//		1950     29.27      28.9     0.4 s
//		2000     64.01      64.0     0.0 s
//		2026     75.38      69.0     6.4 s
//		2100    203.92     102.2   101.7 s   ← 1.7 分钟
//
// 1900–2000 吻合到亚秒。2026 差 6 秒，因为 E–M 的 2005–2050 段是 2005 年
// 拟合的，而此后地球自转没有按当时的预期继续变慢。2100 差 101 秒，是因为
// E–M 的远期外推用的是抛物线 −20+32u²，而 S2020 重新定标过。
//
// 6 秒对节气时刻无影响（远小于 1 分钟容差）。101 秒 = 1.7 分钟，
// 这就是为什么验收标准对 2050 年后放宽到 3 分钟——不是为了给实现留余地，
// 是因为两个权威模型之间本来就差这么多。
//
// DeltaT 返回小数年 y 处的 ΔT（秒）。
//
// y 要带月份的小数部分：y = 年 + (月 − 0.5)/12。多项式是按这个约定拟合的，
// 只传整数年会在段边界附近偏出零点几秒。
func DeltaT(y float64) float64 {
	switch {
	case y < -500:
		u := (y - 1820) / 100
		return -20 + 32*u*u

	case y < 500:
		u := y / 100
		return poly(u, 10583.6, -1014.41, 33.78311, -5.952053,
			-0.1798452, 0.022174192, 0.0090316521)

	case y < 1600:
		u := (y - 1000) / 100
		return poly(u, 1574.2, -556.01, 71.23472, 0.319781,
			-0.8503463, -0.005050998, 0.0083572073)

	case y < 1700:
		t := y - 1600
		return poly(t, 120, -0.9808, -0.01532, 1.0/7129)

	case y < 1800:
		t := y - 1700
		return poly(t, 8.83, 0.1603, -0.0059285, 0.00013336, -1.0/1174000)

	case y < 1860:
		t := y - 1800
		return poly(t, 13.72, -0.332447, 0.0068612, 0.0041116, -0.00037436,
			0.0000121272, -0.0000001699, 0.000000000875)

	case y < 1900:
		t := y - 1860
		return poly(t, 7.62, 0.5737, -0.251754, 0.01680668,
			-0.0004473624, 1.0/233174)

	case y < 1920:
		t := y - 1900
		return poly(t, -2.79, 1.494119, -0.0598939, 0.0061966, -0.000197)

	case y < 1941:
		t := y - 1920
		return poly(t, 21.20, 0.84493, -0.076100, 0.0020936)

	case y < 1961:
		t := y - 1950
		return poly(t, 29.07, 0.407, -1.0/233, 1.0/2547)

	case y < 1986:
		t := y - 1975
		return poly(t, 45.45, 1.067, -1.0/260, -1.0/718)

	case y < 2005:
		t := y - 2000
		return poly(t, 63.86, 0.3345, -0.060374, 0.0017275,
			0.000651814, 0.00002373599)

	case y < 2050:
		t := y - 2000
		return poly(t, 62.92, 0.32217, 0.005589)

	case y < 2150:
		u := (y - 1820) / 100
		return -20 + 32*u*u - 0.5628*(2150-y)

	default:
		u := (y - 1820) / 100
		return -20 + 32*u*u
	}
}

// poly 按升幂求值：c[0] + c[1]x + c[2]x² + …
// 用 Horner 法，避免高次项先算出巨大中间值再相减掉精度
// （1800–1860 段是 7 次多项式，直接展开在 t 接近 60 时会丢有效位）。
func poly(x float64, c ...float64) float64 {
	r := 0.0
	for i := len(c) - 1; i >= 0; i-- {
		r = r*x + c[i]
	}
	return r
}

// deltaTAt 是给内部用的便捷包装：把「年 + 月」换算成多项式要的小数年。
func deltaTAt(year, month int) float64 {
	return DeltaT(float64(year) + (float64(month)-0.5)/12)
}
